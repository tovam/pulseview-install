#!/usr/bin/env bash
set -Eeuo pipefail
IFS=$'\n\t'

trap 'rc=$?; echo >&2 "ERROR: exit $rc at line $LINENO: $BASH_COMMAND"; echo >&2 "PWD: $PWD"; exit $rc' ERR

# Run like: DEBUG=1 ./install.sh
if [[ "${DEBUG:-0}" == "1" ]]; then
  export PS4='+ [${BASH_SOURCE##*/}:${LINENO}] '
  set -x
fi

WORKDIR="${WORKDIR:-$PWD/sigrok-build}"
JOBS="${JOBS:-$(nproc)}"

mkdir -p "$WORKDIR"
cd "$WORKDIR"

echo "== System info =="
uname -a || true
echo "WORKDIR=$WORKDIR"
echo

echo "== Installing build dependencies (apt) =="
sudo apt update
sudo apt install -y \
  git build-essential pkg-config \
  autoconf automake libtool gettext \
  cmake \
  libglib2.0-dev libglibmm-2.4-dev \
  libsigrokcxx-dev \
  qtbase5-dev qttools5-dev libqt5svg5-dev \
  libboost-dev libboost-filesystem-dev libboost-serialization-dev \
  sdcc

# Avoid accidentally using distro libsigrokdecode headers
sudo apt remove -y libsigrokdecode-dev || true

echo
echo "== Tool versions (system) =="
echo "git:        $(command -v git)"; git --version
echo "pkg-config: $(command -v pkg-config)"; /usr/bin/pkg-config --version || true
echo "cmake:      $(command -v cmake)"; cmake --version | head -n 1 || true
echo "g++:        $(command -v g++)"; /usr/bin/g++ --version | head -n 1 || true
echo

# ----------------------------
# Build libsigrokdecode
# ----------------------------
echo "== Cloning & building libsigrokdecode (no install) =="
if [[ ! -d libsigrokdecode/.git ]]; then
  git clone git://sigrok.org/libsigrokdecode
else
  (cd libsigrokdecode && git pull --ff-only)
fi

cd libsigrokdecode
./autogen.sh
./configure
make -j"$JOBS"

# Locate built library directory
LIBSRD_SO="$(find "$PWD" -type f -path "*/.libs/libsigrokdecode.so*" | head -n 1 || true)"
LIBSRD_A="$(find "$PWD" -type f -path "*/.libs/libsigrokdecode.a"  | head -n 1 || true)"
if [[ -n "${LIBSRD_SO}" ]]; then
  LIBSRD_LIBDIR="$(dirname "$LIBSRD_SO")"
elif [[ -n "${LIBSRD_A}" ]]; then
  LIBSRD_LIBDIR="$(dirname "$LIBSRD_A")"
else
  echo >&2 "ERROR: Could not find built libsigrokdecode in .libs/"
  exit 1
fi

# Locate headers in the build tree
LIBSRD_HDR="$PWD/libsigrokdecode.h"
if [[ ! -f "$LIBSRD_HDR" ]]; then
  # fallback search
  LIBSRD_HDR="$(find "$PWD" -maxdepth 5 -type f -name "libsigrokdecode.h" | head -n 1 || true)"
fi
if [[ -z "${LIBSRD_HDR}" || ! -f "$LIBSRD_HDR" ]]; then
  echo >&2 "ERROR: Could not find libsigrokdecode.h in the source tree."
  exit 1
fi

# version.h is typically generated by configure in the build dir
LIBSRD_VER_HDR="$PWD/version.h"
if [[ ! -f "$LIBSRD_VER_HDR" ]]; then
  # fallback search (sometimes under src/ or similar)
  LIBSRD_VER_HDR="$(find "$PWD" -maxdepth 3 -type f -name "version.h" | head -n 1 || true)"
fi
if [[ -z "${LIBSRD_VER_HDR}" || ! -f "$LIBSRD_VER_HDR" ]]; then
  echo >&2 "ERROR: Could not find generated version.h in libsigrokdecode build tree."
  echo >&2 "Tried: $PWD/version.h and a shallow find."
  exit 1
fi

echo "libsigrokdecode.h: $LIBSRD_HDR"
echo "version.h:         $LIBSRD_VER_HDR"
echo "lib dir:           $LIBSRD_LIBDIR"
echo

echo "== Checking required API symbols in built header =="
if grep -q "SRD_OUTPUT_LOGIC" "$LIBSRD_HDR"; then
  echo "OK: SRD_OUTPUT_LOGIC present"
else
  echo >&2 "ERROR: SRD_OUTPUT_LOGIC NOT present in $LIBSRD_HDR"
  exit 1
fi
echo

cd "$WORKDIR"

# ----------------------------
# Include overlay so PulseView can do:
#   #include <libsigrokdecode/libsigrokdecode.h>
# and libsigrokdecode.h can do:
#   #include "version.h"
# ----------------------------
echo "== Creating include overlay for libsigrokdecode include layout =="
INC_OVERLAY="$WORKDIR/_include_overlay"
mkdir -p "$INC_OVERLAY/libsigrokdecode"

ln -sf "$WORKDIR/libsigrokdecode/libsigrokdecode.h" "$INC_OVERLAY/libsigrokdecode/libsigrokdecode.h"
ln -sf "$LIBSRD_VER_HDR" "$INC_OVERLAY/libsigrokdecode/version.h"

echo "Overlay include dir: $INC_OVERLAY"
echo "  libsigrokdecode.h -> $INC_OVERLAY/libsigrokdecode/libsigrokdecode.h"
echo "  version.h         -> $INC_OVERLAY/libsigrokdecode/version.h"
echo

# pkg-config override for libsigrokdecode (so PulseView's version check passes)
PCDIR="$WORKDIR/_pkgconfig"
mkdir -p "$PCDIR"
cat > "$PCDIR/libsigrokdecode.pc" <<EOF
prefix=$WORKDIR
exec_prefix=\${prefix}
libdir=$LIBSRD_LIBDIR
includedir=$INC_OVERLAY

Name: libsigrokdecode
Description: sigrok decoder library (build-tree override)
Version: 0.5.2
Libs: -L\${libdir} -lsigrokdecode
Cflags: -I\${includedir}
EOF

export PKG_CONFIG_PATH="$PCDIR:${PKG_CONFIG_PATH:-}"
export LD_LIBRARY_PATH="$LIBSRD_LIBDIR:${LD_LIBRARY_PATH:-}"

echo "== pkg-config resolution (must be our override) =="
/usr/bin/pkg-config --modversion libsigrokdecode
/usr/bin/pkg-config --cflags --libs libsigrokdecode
echo

# ----------------------------
# Build fx2lafw firmware
# ----------------------------
echo "== Cloning & building sigrok-firmware-fx2lafw (no install) =="
if [[ ! -d sigrok-firmware-fx2lafw/.git ]]; then
  git clone git://sigrok.org/sigrok-firmware-fx2lafw
else
  (cd sigrok-firmware-fx2lafw && git pull --ff-only)
fi

cd sigrok-firmware-fx2lafw
./autogen.sh
./configure
make -j"$JOBS"

echo
echo "Built firmware files (examples):"
find "$PWD" -type f \( -name "*.hex" -o -name "*.ihx" -o -name "*.fw" \) | head -n 20 || true
echo

cd "$WORKDIR"

# ----------------------------
# Build PulseView
# ----------------------------
echo "== Cloning & building PulseView =="
if [[ ! -d pulseview/.git ]]; then
  git clone git://sigrok.org/pulseview.git
else
  (cd pulseview && git pull --ff-only)
fi

cd pulseview

echo "== Applying Glib DateTime -> TimeVal compatibility patch (if needed) =="
if grep -q 'create_header_packet(session_\.get_acquisition_start_time());' pv/storesession.cpp; then
  perl -0777 -i -pe 's/auto header = context->create_header_packet\(session_\.get_acquisition_start_time\(\)\);/const auto dt = session_.get_acquisition_start_time();\n\t\t\t\tGlib::TimeVal tv;\n\t\t\t\ttv.tv_sec  = static_cast<glong>(dt.to_unix());\n\t\t\t\ttv.tv_usec = static_cast<glong>(dt.get_microsecond());\n\n\t\t\t\tauto header = context->create_header_packet(tv);/g' pv/storesession.cpp
  echo "Patched pv/storesession.cpp"
else
  echo "Patch not applied (already patched or source differs)."
fi
echo

rm -rf build
mkdir -p build

CMAKE_EXTRA=()
if [[ "${DEBUG:-0}" == "1" ]]; then
  CMAKE_EXTRA+=(-DCMAKE_FIND_DEBUG_MODE=ON)
fi

echo "== Configuring (cmake) with forced compilers + forced libsigrokdecode include/lib dirs =="
echo "Forcing include: -I$INC_OVERLAY"
echo "Forcing libdir : -L$LIBSRD_LIBDIR"
echo

cmake -S . -B build \
  -DCMAKE_C_COMPILER=/usr/bin/gcc \
  -DCMAKE_CXX_COMPILER=/usr/bin/g++ \
  -DPKG_CONFIG_EXECUTABLE=/usr/bin/pkg-config \
  -DCMAKE_CXX_FLAGS="-I$INC_OVERLAY" \
  -DCMAKE_EXE_LINKER_FLAGS="-L$LIBSRD_LIBDIR" \
  -DCMAKE_BUILD_RPATH="$LIBSRD_LIBDIR" \
  -DCMAKE_INSTALL_RPATH="$LIBSRD_LIBDIR" \
  "${CMAKE_EXTRA[@]}"


echo
echo "== Building (cmake --build) =="
cmake --build build -j"$JOBS" --verbose

echo
echo "== Done =="
echo "PulseView binary: $WORKDIR/pulseview/build/pulseview"
echo


